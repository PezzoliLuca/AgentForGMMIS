"""Pydantic schemas and contracts for the AuditorAgent ('Il Vigile')."""

from enum import Enum
from typing import Any, List, Optional, Tuple
from pydantic import BaseModel, Field

from agent_gmmis.extraction.schemas import RawExtractedScore


class AuditStatus(str, Enum):
    """Overall certification status issued by the Auditor."""

    VERIFIED = "verified"
    FLAGGED_WARNING = "flagged_warning"
    REJECTED = "rejected"
    NEEDS_OUTREACH = "needs_outreach"
    NEEDS_REPO_INSPECTION = "needs_repo_inspection"


class MissingDataDiagnosis(str, Enum):
    """Diagnosis when quantitative scalar tables are absent in manuscript."""

    NONE = "none"
    MISSING_TABLE_FIGURES_FOUND = "missing_table_figures_found"
    MISSING_TABLE_NO_DATA = "missing_table_no_data"
    CODE_REPO_AVAILABLE = "code_repo_available"


class AuditAnomaly(BaseModel):
    """Detailed record of an unexpected value, out-of-scale parameter, or discrepancy."""

    field: str
    severity: str = Field("warning", description="'warning' or 'critical'")
    message: str
    extracted_value: Any = None
    expected_range: Optional[Tuple[float, float]] = None


class OutlierDetectionResult(BaseModel):
    """Statistical outlier record comparing an extracted score against historical database distributions."""

    dataset_name: str
    extracted_score: float
    historical_min: float
    historical_max: float
    historical_mean: float
    historical_count: int
    is_outlier: bool
    reason: Optional[str] = None


class DiscrepancyNotice(BaseModel):
    """Documents divergence between fresh extraction and existing human survey records (e.g. human typos)."""

    dataset_name: str
    extracted_score: float
    survey_ground_truth: float
    delta: float
    message: str


class AuditReport(BaseModel):
    """Comprehensive certification report generated by the AuditorAgent."""

    model_id: str
    status: AuditStatus
    passed_sanity_checks: bool
    passed_inclusion_screening: bool
    rejection_reasons: List[str] = Field(default_factory=list)
    anomalies: List[AuditAnomaly] = Field(default_factory=list)
    outliers: List[OutlierDetectionResult] = Field(default_factory=list)
    discrepancies: List[DiscrepancyNotice] = Field(default_factory=list)
    data_diagnosis: MissingDataDiagnosis = MissingDataDiagnosis.NONE
    confidence_score: float = Field(1.0, description="Confidence score from 0.0 to 1.0")
    summary: str = ""
    validated_scores: List[RawExtractedScore] = Field(default_factory=list, description="Validated numerical scores carried over from extraction")


class RepoInspectionResult(BaseModel):
    """Result of inspecting an official code repository for quantitative benchmarks."""

    repo_url: str = Field(..., description="Target repository URL (e.g. GitHub URL)")
    success: bool = Field(False, description="True if quantitative benchmarks were successfully extracted")
    extracted_scores: List[RawExtractedScore] = Field(
        default_factory=list,
        description="List of benchmark scores extracted from repository artifacts",
    )
    inspected_files: List[str] = Field(
        default_factory=list,
        description="Relative file paths inspected within the repository",
    )
    message: str = Field("", description="Status message, summary, or error explanation")
    cache_path: Optional[str] = Field(None, description="Local filesystem path where repository is cached")


class OutreachStatus(str, Enum):
    """Lifecycle status of an academic inquiry email draft."""

    DRAFT_PENDING_REVIEW = "draft_pending_review"
    APPROVED = "approved"
    DISPATCHED = "dispatched"
    REPLIED = "replied"


class AuthorContactInfo(BaseModel):
    """Extracted contact information for paper correspondence."""

    name: str = Field(..., description="Full name of corresponding author")
    email: Optional[str] = Field(None, description="Primary academic email address")
    affiliation: Optional[str] = Field(None, description="University, hospital, or institute affiliation")
    is_corresponding: bool = Field(False, description="True if marked explicitly as corresponding author")
    confidence: float = Field(1.0, description="Extraction confidence score [0.0, 1.0]")


class OutreachDraft(BaseModel):
    """Complete academic inquiry draft generated by the OutreachAgent."""

    model_id: str = Field(..., description="Target model identifier (e.g. Merlin, Med-SA)")
    paper_title: str = Field(..., description="Full scientific paper title")
    recipient: AuthorContactInfo = Field(..., description="Target recipient contact details")
    target_datasets: List[str] = Field(
        default_factory=list,
        description="List of benchmark datasets where scalar metrics are needed",
    )
    target_figures: List[str] = Field(
        default_factory=list,
        description="Specific figure or chart references depicting graphical metrics",
    )
    email_subject: str = Field(..., description="Standardized academic inquiry subject line")
    email_body: str = Field(..., description="Formal collegial email text in English")
    created_at: str = Field(..., description="ISO timestamp of draft generation")
    status: OutreachStatus = Field(
        OutreachStatus.DRAFT_PENDING_REVIEW,
        description="Human-in-the-loop review status",
    )
    notes: Optional[str] = Field(None, description="Internal notes or context for reviewer")
    draft_filepath: Optional[str] = Field(None, description="Path where JSON draft is saved")


class ConsensusStatus(str, Enum):
    """Agreement status between dual extraction agents."""

    CONCORDANT = "concordant"
    DISPUTED = "disputed"
    SINGLE_AGENT_UNCONFIRMED = "single_agent_unconfirmed"


class ConsensusScore(BaseModel):
    """Individual benchmark score evaluated under dual-agent consensus."""

    dataset_name: str
    canonical_dataset_name: str
    organ_or_task: Optional[str] = None
    status: ConsensusStatus
    score_a: Optional[float] = None
    score_b: Optional[float] = None
    resolved_score: Optional[float] = Field(
        None,
        description="Unified score if concordant or verified; None if disputed.",
    )
    delta: Optional[float] = Field(
        None,
        description="Absolute difference between score_a and score_b when both are present.",
    )
    table_ref_a: Optional[str] = None
    table_ref_b: Optional[str] = None
    prompt_type: Optional[str] = None
    data_budget_or_setting: Optional[str] = None
    notes: Optional[str] = None


class ConsensusScreening(BaseModel):
    """Consensus agreement on inclusion screening criteria."""

    status: ConsensusStatus
    is_included: bool
    is_3d_a: bool
    is_3d_b: bool
    is_radiological_a: bool
    is_radiological_b: bool
    is_public_a: bool
    is_public_b: bool
    has_dice_a: bool
    has_dice_b: bool
    notes: Optional[str] = None


class ConsensusMetadata(BaseModel):
    """Consensus agreement on architectural parameters and model metadata."""

    model_id_status: ConsensusStatus
    resolved_model_id: str
    model_id_a: str
    model_id_b: str
    params_status: ConsensusStatus
    resolved_params_m: Optional[float] = None
    params_m_a: Optional[float] = None
    params_m_b: Optional[float] = None
    visual_backbone_a: Optional[str] = None
    visual_backbone_b: Optional[str] = None
    resolved_visual_backbone: Optional[str] = None
    code_repository_url: Optional[str] = None
    notes: Optional[str] = None


class ConsensusAuditReport(BaseModel):
    """Comprehensive dual-agent consensus and arbitration certificate."""

    model_id: str
    status: AuditStatus
    consensus_scores: List[ConsensusScore] = Field(default_factory=list)
    consensus_screening: ConsensusScreening
    consensus_metadata: ConsensusMetadata
    inter_model_dice_mae: Optional[float] = Field(
        None,
        description="Mean absolute difference across paired benchmark scores between Model A and Model B.",
    )
    concordance_rate: float = Field(
        0.0,
        description="Percentage of common benchmarks that are concordant within tolerance.",
    )
    concordant_count: int = 0
    dispute_count: int = 0
    unconfirmed_count: int = 0
    paired_count: int = 0
    total_unique_benchmarks: int = 0
    audit_report_a: AuditReport
    audit_report_b: AuditReport
    confidence_score: float = Field(1.0, description="Overall certified confidence score [0.0, 1.0]")
    summary: str = ""

    @property
    def passed_sanity_checks(self) -> bool:
        """True if both agents passed numerical and architectural sanity checks."""
        return self.audit_report_a.passed_sanity_checks and self.audit_report_b.passed_sanity_checks

    @property
    def passed_inclusion_screening(self) -> bool:
        """True if consensus resolved inclusion criteria as eligible."""
        return self.consensus_screening.is_included

    @property
    def rejection_reasons(self) -> List[str]:
        """Consolidated list of unique rejection reasons across both agents."""
        return list(dict.fromkeys(self.audit_report_a.rejection_reasons + self.audit_report_b.rejection_reasons))

    @property
    def anomalies(self) -> List[AuditAnomaly]:
        """Consolidated list of anomalies flagged across both agents."""
        return self.audit_report_a.anomalies + self.audit_report_b.anomalies

    @property
    def outliers(self) -> List[OutlierDetectionResult]:
        """Consolidated list of statistical outliers flagged across both agents."""
        return self.audit_report_a.outliers + self.audit_report_b.outliers

    @property
    def discrepancies(self) -> List[DiscrepancyNotice]:
        """Consolidated list of human survey discrepancies intercepted across both agents."""
        return self.audit_report_a.discrepancies + self.audit_report_b.discrepancies

    @property
    def data_diagnosis(self) -> MissingDataDiagnosis:
        """Consensus missing data diagnosis."""
        if self.audit_report_a.data_diagnosis != MissingDataDiagnosis.NONE:
            return self.audit_report_a.data_diagnosis
        return self.audit_report_b.data_diagnosis
